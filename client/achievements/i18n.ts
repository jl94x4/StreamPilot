export const tAchievements = (
    key: string,
    vars?: Record<string, string | number>,
    locale?: DiscoverLocale,
) => {
    const code = locale || readDiscoverUiLocale();
    const catalog = catalogs[code] || catalogs.en;
    let text = catalog[key] || catalogs.en[key] || key;
    if (vars) {
        for (const [name, value] of Object.entries(vars)) {
            text = text.replace(new RegExp(`\\{${name}\\}`, 'g'), String(value));
        }
    }
    return text;
};

export const useAchievementsI18n = () => {
    const { locale } = useDiscoverI18n();
    const tAchievementsForLocale = useCallback((
        key: string,
        vars?: Record<string, string | number>,
    ) => tAchievements(key, vars, locale), [locale]);
    return { locale, tAchievements: tAchievementsForLocale };
};
