import fs from 'fs/promises';
import path from 'path';
import { resolveSpotifyToPlexScheduleMode } from './spotify-to-plex-schedule-mode.js';

export const SPOTIFY_TO_PLEX_ENV_FILE_NAME = 'spotify-to-plex.env';
export const SPOTIFY_TO_PLEX_PLEX_APP_ID = 'eXf+f9ktw3CZ8i45OY468WxriOCtoFxuNPzVeDcAwfw=';

export const getSpotifyToPlexEnvFilePath = (configDir) => (
    path.join(String(configDir || ''), SPOTIFY_TO_PLEX_ENV_FILE_NAME)
);

/** Whether portal config has the secrets needed for OAuth + container env_file. */
export const isSpotifyToPlexCredentialsReady = (config = {}) => (
    !!String(config.spotifyToPlexClientId || '').trim()
    && !!String(config.spotifyToPlexClientSecret || '').trim()
    && !!String(config.spotifyToPlexEncryptionKey || '').trim()
);

/**
 * Write docker env_file consumed by the spotify-to-plex Compose service.
 * Credentials live in portal Settings — not the host .env.
 */
export const syncSpotifyToPlexSidecarEnv = async (
    config,
    {
        configDir,
        withBasePath,
        resolvePublicBaseUrlFromConfig,
        resolveSpotifyToPlexCallbackUrl,
        log = () => {},
    } = {},
) => {
    const filePath = getSpotifyToPlexEnvFilePath(configDir);
    if (!config?.spotifyToPlexEnabled) {
        try {
            await fs.unlink(filePath);
        } catch {
            // ignore missing file
        }
        return { written: false, removed: true };
    }

    const callbackUrl = resolveSpotifyToPlexCallbackUrl?.(config, withBasePath, resolvePublicBaseUrlFromConfig) || '';
    if (!isSpotifyToPlexCredentialsReady(config) || !callbackUrl) {
        return { written: false, missing: true, path: filePath };
    }

    const lines = [
        '# Generated by StreamPilot (Settings → Spotify Sync). Restart spotify-to-plex after changes.',
        `# Schedule mode: ${resolveSpotifyToPlexScheduleMode(config)}`,
        `SPOTIFY_API_CLIENT_ID=${String(config.spotifyToPlexClientId).trim()}`,
        `SPOTIFY_API_CLIENT_SECRET=${String(config.spotifyToPlexClientSecret).trim()}`,
        `ENCRYPTION_KEY=${String(config.spotifyToPlexEncryptionKey).trim()}`,
        `SPOTIFY_API_REDIRECT_URI=${callbackUrl}`,
        `PLEX_APP_ID=${SPOTIFY_TO_PLEX_PLEX_APP_ID}`,
        'SYNC_ON_STARTUP=false',
        `TZ=${String(process.env.TZ || 'UTC').trim() || 'UTC'}`,
    ];
    const nextBody = `${lines.join('\n')}\n`;
    try {
        const current = await fs.readFile(filePath, 'utf8');
        if (current === nextBody) {
            return { written: false, unchanged: true, path: filePath };
        }
    } catch {
        // missing or unreadable — write
    }
    await fs.mkdir(path.dirname(filePath), { recursive: true });
    await fs.writeFile(filePath, nextBody, { mode: 0o600 });
    log(`[spotify-sync] Wrote spotify-to-plex env_file at ${filePath}`);
    return { written: true, path: filePath };
};
