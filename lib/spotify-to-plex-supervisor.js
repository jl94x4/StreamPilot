import fs from 'fs/promises';
import path from 'path';
import { isSpotifyPortalScheduleMode, resolveSpotifyToPlexScheduleMode } from './spotify-to-plex-schedule-mode.js';

export const SPOTIFY_TO_PLEX_SUPERVISOR_FILE_NAME = 'supervisord.conf';

export const getSpotifyToPlexSupervisorFilePath = (configDir) => (
    path.join(String(configDir || ''), 'spotify-to-plex', SPOTIFY_TO_PLEX_SUPERVISOR_FILE_NAME)
);

/**
 * Supervisor config for jjdenhertog/spotify-to-plex (sync-scheduler program).
 * Portal schedule mode disables the container sync-scheduler so only one scheduler runs.
 */
export const buildSpotifyToPlexSupervisordConf = (config = {}) => {
    const portalSchedule = isSpotifyPortalScheduleMode(config);
    const syncSchedulerAutostart = portalSchedule ? 'false' : 'true';
    const modeLabel = resolveSpotifyToPlexScheduleMode(config);
    return `# Generated by StreamPilot (Settings → Spotify Sync).
# Schedule mode: ${modeLabel}. Restart spotify-to-plex after changes.
[supervisord]
nodaemon=true
user=root
logfile=/var/log/supervisor/supervisord.log
pidfile=/var/run/supervisord.pid
childlogdir=/var/log/supervisor

[unix_http_server]
file=/var/run/supervisor.sock
chmod=0700

[supervisorctl]
serverurl=unix:///var/run/supervisor.sock

[rpcinterface:supervisor]
supervisor.rpcinterface_factory = supervisor.rpcinterface:make_main_rpcinterface

[program:spotify-scraper]
command=python3 app.py
directory=/app/apps/spotify-scraper
autostart=true
autorestart=true
environment=PORT="3020",HOST="0.0.0.0",PYTHONPATH="/app/apps/spotify-scraper"
priority=100
startsecs=10
startretries=3
stderr_logfile=/var/log/supervisor/spotify-scraper-stderr.log
stdout_logfile=/var/log/supervisor/spotify-scraper-stdout.log

[program:web]
command=node apps/web/server.js
directory=/app/web
autostart=true
autorestart=true
environment=PORT="9030",HOSTNAME="0.0.0.0",SPOTIFY_SCRAPER_URL="http://localhost:3020",NODE_ENV="production"
priority=200
startsecs=15
startretries=3
stderr_logfile=/var/log/supervisor/web-stderr.log
stdout_logfile=/var/log/supervisor/web-stdout.log

[program:sync-scheduler]
command=npx tsx src/scheduler.ts
directory=/app/apps/sync-worker
autostart=${syncSchedulerAutostart}
autorestart=${syncSchedulerAutostart}
environment=NODE_ENV="production",TZ="%(ENV_TZ)s",SYNC_ON_STARTUP="%(ENV_SYNC_ON_STARTUP)s"
priority=300
startsecs=5
startretries=3
stderr_logfile=/var/log/supervisor/sync-scheduler-stderr.log
stdout_logfile=/var/log/supervisor/sync-scheduler-stdout.log
`;
};

export const syncSpotifyToPlexSupervisorConfig = async (
    config,
    { configDir, log = () => {} } = {},
) => {
    const filePath = getSpotifyToPlexSupervisorFilePath(configDir);
    if (!config?.spotifyToPlexEnabled) {
        try {
            await fs.unlink(filePath);
        } catch {
            // ignore missing file
        }
        return { written: false, removed: true };
    }

    const contents = buildSpotifyToPlexSupervisordConf(config);
    await fs.mkdir(path.dirname(filePath), { recursive: true });
    await fs.writeFile(filePath, contents, { mode: 0o644 });
    const mode = resolveSpotifyToPlexScheduleMode(config);
    log(`[spotify-sync] Wrote spotify-to-plex supervisord.conf (${mode} schedule) at ${filePath}`);
    return { written: true, path: filePath, mode };
};
